function headBlock({ title, desc, canonical, robots, ogType = "website", ld, siteVar }) {
  const lines = [
    "<!-- seo:start (generated by tools/seo.mjs — edit that file, then run: node tools/seo.mjs) -->",
    `<title>${esc(title)}</title>`,
    `<meta name="description" content="${esc(desc)}">`
  ];
  if (robots) lines.push(`<meta name="robots" content="${robots}">`);
  if (canonical) lines.push(`<link rel="canonical" href="${esc(canonical)}">`);
  if (GOOGLE_SITE_VERIFICATION) lines.push(`<meta name="google-site-verification" content="${esc(GOOGLE_SITE_VERIFICATION)}">`);
  if (BING_SITE_VERIFICATION) lines.push(`<meta name="msvalidate.01" content="${esc(BING_SITE_VERIFICATION)}">`);
  lines.push(
    '<meta name="theme-color" content="#3669EE">',
    '<link rel="icon" href="assets/brand/favicon-48.png" sizes="48x48" type="image/png">',
    '<link rel="icon" href="assets/brand/icon-192.png" sizes="192x192" type="image/png">',
    '<link rel="apple-touch-icon" href="assets/brand/apple-touch-icon.png">',
    `<meta property="og:site_name" content="${esc(CLINIC.name)}">`,
    '<meta property="og:locale" content="fa_IR">',
    `<meta property="og:type" content="${ogType}">`,
    `<meta property="og:title" content="${esc(title)}">`,
    `<meta property="og:description" content="${esc(desc)}">`
  );
  if (canonical) lines.push(`<meta property="og:url" content="${esc(canonical)}">`);
  lines.push(
    `<meta property="og:image" content="${abs(OG_IMAGE)}">`,
    '<meta property="og:image:width" content="1200">',
    '<meta property="og:image:height" content="630">',
    '<meta name="twitter:card" content="summary_large_image">',
    '<link rel="preconnect" href="https://unpkg.com" crossorigin>',
    '<link rel="preload" href="uploads/YekanBakhFaNum-Regular.woff2" as="font" type="font/woff2" crossorigin>',
    '<link rel="preload" href="uploads/YekanBakhFaNum-ExtraBold.woff2" as="font" type="font/woff2" crossorigin>'
  );
  if (siteVar) lines.push(`<script>window.NIKAN_SITE_URL = ${JSON.stringify(SITE_URL)};</script>`);
  if (ld) lines.push(jsonLd({ "@context": "https://schema.org", "@graph": ld }));
  lines.push("<!-- seo:end -->");
  return lines.join("\n");
}

