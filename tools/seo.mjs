function noscriptBlock(intro) {
  return [
    "<!-- seo-noscript:start (generated by tools/seo.mjs) -->",
    `<noscript><div dir="rtl" lang="fa" style="${noscriptStyle}">`,
    `<p><strong>${esc(CLINIC.name)}</strong> — ${esc(intro)}</p>`,
    "<p>برای جست‌وجوی پزشک و دریافت نوبت، جاوااسکریپت مرورگر را فعال کنید.</p>",
    "<h2>پزشکان کلینیک</h2>",
    `<ul>\n${doctorList}\n</ul>`,
    "<h2>اطلاعات تماس و مراجعه</h2>",
    `<ul>\n${contactList}\n</ul>`,
    "</div></noscript>",
    "<!-- seo-noscript:end -->"
  ].join("\n");
}

function replaceBlock(src, start, end, block, file) {
  const re = new RegExp("<!-- " + start + "[\\s\\S]*?<!-- " + end + " -->");
  if (!re.test(src)) throw new Error(`Marker <!-- ${start} --> missing in ${file}`);
  return src.replace(re, () => block);
}

