// Builds the search-engine files for the Nikan Clinic site:
//   - the <!-- seo:start --> ... <!-- seo:end --> block in each page's <head>
//     (title, description, canonical, social preview tags, structured data)
//   - the <!-- seo-noscript:start --> ... <!-- seo-noscript:end --> block (plain HTML
//     for visitors and crawlers that do not run JavaScript)
//   - sitemap.xml and robots.txt
//
// Run it again after changing the address, doctors or site URL:
//   node tools/seo.mjs
//
// Every fact below must match what the pages show. Do not add anything here
// that is not on the site.

